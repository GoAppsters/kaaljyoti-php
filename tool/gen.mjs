/**
 * Words PHP will not accept as a property name.
 *
 * Far shorter than Dart's list: PHP has kept reserved words legal as member
 * names since 7.0, and `$this` is the only one a property cannot be called.
 * The snapshot has no such key today; the guard is here so a future one is
 * renamed instead of emitting a parse error.
 */
const RESERVED = new Set(['this']);

/** `utc_offset` / `UtcOffset` / `utcOffset` → `['utc', 'offset']`. */
function words(name) {
  return name
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean);
}

function pascal(name) {
  return words(name)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join('');
}

function camel(name) {
  const p = pascal(name);
  const lower = p[0].toLowerCase() + p.slice(1);
  return RESERVED.has(lower) ? `${lower}Value` : lower;
}

/** `whole_sign` → `WHOLE_SIGN`, the name a PHP class constant goes by. */
function constantName(value) {
  return words(value)
    .map((w) => w.toUpperCase())
    .join('_');
}

