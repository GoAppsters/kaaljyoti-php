#!/usr/bin/env node
/**
 * `openapi/openapi.json` → `src/Models/*.php` and `src/Generated/*.php`.
 *
 * Design decision 3: generated models, our generator. This follows the Dart
 * generator (`packages/sdk-dart/tool/gen.mjs`) rule for rule — the same
 * `REQUEST_NAMES` table, the same shape-based dedupe so `Birth`,
 * `CalculationOptions` and `TimeWindow` exist once rather than 35 times, the
 * same hand-picked names for the four shapes that dedupe into something a
 * path-derived name would not describe, `LabelledId` shared, `null`-only
 * fields as the widest type the language has, `MaitriDocument` as a wrapper
 * around the map it is, and reference rows left untyped. The three SDKs are
 * read side by side, so a shape must not be `ChalitHouses` in Dart and
 * `ChalitDocumentEqual` here.
 *
 * Where the files go, and why they are not all in one directory:
 * `composer.json` maps the PSR-4 prefix `Kaaljyoti\` to `src/`, so PSR-4 looks
 * for `Kaaljyoti\Models\KundliDocument` in `src/Models/KundliDocument.php` —
 * a `src/Generated/Models/` directory could not hold it without a second
 * autoload entry. So the models take the namespace callers type
 * (`Kaaljyoti\Models`) and live in `src/Models/`, and the three files that are
 * plumbing rather than payload — the cast helpers, the operation table and the
 * version constants — take `Kaaljyoti\Generated` and live in `src/Generated/`.
 * `LabelledId` is plumbing by that rule and is generated into
 * `src/Generated/LabelledId.php`; every model that names an id imports it.
 *
 * What it writes:
 *
 *   src/Generated/Json.php        cast helpers (PHPStan level 9 rejects `mixed`)
 *   src/Generated/LabelledId.php  the one shape every document shares
 *   src/Generated/Operation.php   one row of the operation table
 *   src/Generated/Operations.php  the table itself, which the contract test walks
 *   src/Generated/Version.php     the two version constants
 *   src/Models/<ClassName>.php    one final readonly class per schema
 *
 * There is no PHP formatter in this workspace, so the emitted bytes are the
 * committed bytes: PSR-12 by construction (4-space indent, `declare`d strict
 * types, one class per file). `--check` regenerates into memory and compares
 * byte for byte, so CI fails on a stale file rather than shipping models that
 * describe an API we no longer have.
 *
 * Usage: `node tool/gen.mjs [--check]`.
 */

