function quote(text) {
  return `'${String(text).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

/** PSR-12's soft limit, which the emitted lines keep to wherever they can. */
const WIDTH = 120;

/** `text` broken on spaces into lines of at most `width` characters. */
function wrap(text, width) {
  const out = [];
  let line = '';
  for (const word of text.split(' ')) {
    if (line === '') line = word;
    else if (`${line} ${word}`.length <= width) line = `${line} ${word}`;
    else {
      out.push(line);
      line = word;
    }
  }
  if (line !== '') out.push(line);
  return out;
}

/**
 * A description as a `/** … *\/` block, with the blank lines OpenAPI allows.
 *
 * The snapshot writes a schema description as one long line; it is wrapped
 * here, and a tag that has to wrap continues indented the way PHPDoc does it.
 */
function docBlock(lines, indent = '') {
  const body = lines.filter((line) => line !== null);
  if (body.length === 0) return [];
  const width = WIDTH - indent.length - 3;
  const wrapped = [];
  for (const line of body) {
    if (line.length <= width) {
      wrapped.push(line);
      continue;
    }
    const [first, ...rest] = wrap(line, width);
    wrapped.push(first);
    for (const more of wrap(rest.join(' '), width - 4)) {
      wrapped.push(line.startsWith('@') ? `    ${more}` : more);
    }
  }
  return [
    `${indent}/**`,
    ...wrapped.map((line) => (line ? `${indent} * ${line}` : `${indent} *`)),
    `${indent} */`,
  ];
}

/**
 * One statement, broken over several lines when it is too long to read.
 *
 * Only `array_map()` ever gets long enough to matter — a map of lists of a
 * class names that class three times in one line — so that is the one call
 * this knows how to open up.
 */
function wrapStatement(line) {
  if (line.length <= WIDTH) return [line];
  const at = line.indexOf('array_map(');
  if (at < 0) return [line];
  const open = at + 'array_map('.length - 1;
  let depth = 0;
  let close = -1;
  for (let i = open; i < line.length; i += 1) {
    if (line[i] === '(') depth += 1;
    else if (line[i] === ')') {
      depth -= 1;
      if (depth === 0) {
        close = i;
        break;
      }
    }
  }
  if (close < 0) return [line];

  const inner = line.slice(open + 1, close);
  const args = [];
  let level = 0;
  let start = 0;
  for (let i = 0; i < inner.length; i += 1) {
    if (inner[i] === '(') level += 1;
    else if (inner[i] === ')') level -= 1;
    else if (inner[i] === ',' && level === 0) {
      args.push(inner.slice(start, i).trim());
      start = i + 1;
    }
  }
  args.push(inner.slice(start).trim());

  const indent = /^\s*/.exec(line)[0];
  const out = [`${line.slice(0, at)}array_map(`];
  for (const arg of args) {
    const closure = /^(static fn \([^)]*\): \S+ )=> (.*)$/.exec(arg);
    if (closure && `${indent}    ${arg},`.length > WIDTH) {
      out.push(`${indent}    ${closure[1].trimEnd()}`);
      out.push(`${indent}        => ${closure[2]},`);
    } else {
      out.push(`${indent}    ${arg},`);
    }
  }
  out.push(`${indent})${line.slice(close + 1)}`);
  return out;
}

/** A schema description, trimmed, as the lines of a doc block. */
function prose(text) {
  if (!text) return [];
  return String(text)
    .trim()
    .split('\n')
    .map((line) => line.replace(/\s+$/, ''));
}

/** A description squashed onto one line, for an `@param` tag. */
function oneLine(text) {
  if (!text) return '';
  return String(text).trim().replace(/\s+/g, ' ');
}

