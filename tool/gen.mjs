/** The `@param` block of a promoted constructor. */
function constructorDoc(fields) {
  const tags = [];
  for (const f of fields) {
    if (!needsDocType(f.type) && !f.description) continue;
    const description = oneLine(f.description);
    tags.push(`@param ${docType(f.type)} $${f.name}${description ? ` ${description}` : ''}`);
  }
  return docBlock(tags, '    ');
}

function emitConstructor(entry) {
  const out = [...constructorDoc(entry.fields)];
  out.push('    public function __construct(');
  for (const f of entry.fields) {
    const suffix = f.type.nullable ? ' = null' : '';
    out.push(`        public ${declared(f.type)} $${f.name}${suffix},`);
  }
  out.push('    ) {');
  out.push('    }');
  return out;
}

function emitFromArray(entry) {
  const out = [
    ...docBlock(['@param array<string, mixed> $data'], '    '),
    '    public static function fromArray(array $data): self',
    '    {',
  ];
  const pre = [];
  const args = [];
  for (const f of entry.fields) {
    const raw = `$data[${quote(f.wire)}] ?? null`;
    if (f.type.kind === 'map') {
      if (f.type.nullable) {
        pre.push(`        $${f.name}Raw = ${raw};`);
        pre.push(`        $${f.name} = null;`);
        pre.push(`        if ($${f.name}Raw !== null) {`);
        pre.push(...readMapLines(`$${f.name}`, f.type, `$${f.name}Raw`, '            '));
        pre.push('        }');
      } else {
        pre.push(...readMapLines(`$${f.name}`, f.type, raw, '        '));
      }
      args.push(`            ${f.name}: $${f.name},`);
      continue;
    }
    if (f.type.kind === 'stringOrClass') {
      // Two guards on one value read better as their own statement than as a
      // nested ternary, which PHP 8 will not parse without parentheses anyway.
      const guard = f.type.nullable
        ? `is_string($${f.name}Raw) || $${f.name}Raw === null`
        : `is_string($${f.name}Raw)`;
      pre.push(`        $${f.name}Raw = ${raw};`);
      pre.push(`        $${f.name} = ${guard}`);
      pre.push(`            ? $${f.name}Raw`);
      pre.push(`            : ${f.type.of.name}::fromArray(Json::object($${f.name}Raw));`);
      args.push(`            ${f.name}: $${f.name},`);
      continue;
    }
    if (f.type.nullable && ['class', 'list'].includes(f.type.kind)) {
      // The guard mentions the value twice, so it is read into a local first.
      pre.push(`        $${f.name}Raw = ${raw};`);
      args.push(`            ${f.name}: ${readExpr(f.type, `$${f.name}Raw`)},`);
      continue;
    }
    args.push(`            ${f.name}: ${readExpr(f.type, raw)},`);
  }
  out.push(...pre);
  if (pre.length > 0) out.push('');
  out.push('        return new self(');
  out.push(...args);
  out.push('        );');
  out.push('    }');
  return out;
}

function emitToArray(entry) {
  const out = [
    ...docBlock(
      ['This value as an array, with every null key left out.', '', '@return array<string, mixed>'],
      '    ',
    ),
    '    public function toArray(): array',
    '    {',
    '        $out = [];',
  ];
  for (const f of entry.fields) {
    const property = `$this->${f.name}`;
    if (!f.type.nullable) {
      const value = writeValue(f.type, property, f.name, '        ');
      out.push(...value.pre);
      out.push(`        $out[${quote(f.wire)}] = ${value.expr};`);
      continue;
    }
    out.push(`        if (${property} !== null) {`);
    if (f.type.kind === 'stringList') {
      // A single language goes out as the bare string the gateway documents.
      out.push(
        `            $out[${quote(f.wire)}] = count(${property}) === 1 ? ${property}[0] : ${property};`,
      );
    } else {
      const value = writeValue({ ...f.type, nullable: false }, property, f.name, '            ');
      out.push(...value.pre);
      out.push(`            $out[${quote(f.wire)}] = ${value.expr};`);
    }
    out.push('        }');
  }
  out.push('');
  out.push('        return $out;');
  out.push('    }');
  return out;
}

/** A document that is a bare map: the class wraps it and reads through. */
function emitMapClass(entry) {
  const value = entry.valueType;
  const out = [
    ...docBlock([`@param array<string, ${docType(value)}> $values`], '    '),
    '    public function __construct(',
    '        public array $values,',
    '    ) {',
    '    }',
    '',
    ...docBlock(
      ['Reads the map, keyed as the API keys it.', '', '@param array<string, mixed> $data'],
      '    ',
    ),
    '    public static function fromArray(array $data): self',
    '    {',
  ];
  if (value.kind === 'map' && !value.nullable) {
    out.push('        $values = [];');
    out.push('        foreach ($data as $key => $value) {');
    out.push(...readMapLines('$inner', value, '$value', '            ', 1));
    out.push('            $values[$key] = $inner;');
    out.push('        }');
  } else {
    out.push('        $values = [];');
    out.push('        foreach ($data as $key => $value) {');
    out.push(`            $values[$key] = ${readExpr(value, '$value', 1)};`);
    out.push('        }');
  }
  out.push('');
  out.push('        return new self($values);');
  out.push('    }');
  out.push('');
  out.push(
    ...docBlock(
      [
        'The entry under $key, or null when the API left it out.',
        '',
        `@return ${docType({ ...value, nullable: true })}`,
      ],
      '    ',
    ),
  );
  out.push(
    `    public function get(string $key): ${declared({ ...value, nullable: true })}`,
    '    {',
    '        return $this->values[$key] ?? null;',
    '    }',
    '',
  );
  out.push(...docBlock(['This document as an array.', '', '@return array<string, mixed>'], '    '));
  out.push('    public function toArray(): array');
  out.push('    {');
  const written = writeValue(value, '$value', 'values', '            ', 1);
  if (writesPlainly(value)) {
    out.push('        return $this->values;');
  } else {
    out.push('        $out = [];');
    out.push('        foreach ($this->values as $key => $value) {');
    out.push(...written.pre);
    out.push(`            $out[$key] = ${written.expr};`);
    out.push('        }');
    out.push('');
    out.push('        return $out;');
  }
  out.push('    }');
  return out;
}

function emitClass(entry) {
  const raw = entry.valueType
    ? emitMapClass(entry)
    : [...emitConstructor(entry), '', ...emitFromArray(entry), '', ...emitToArray(entry)];
  const body = raw.flatMap(wrapStatement);
  const description = prose(entry.description);
  return [
    ...docBlock([
      ...description,
      ...(description.length > 0 ? [''] : []),
      `Wire shape: \`${entry.origin}\`.`,
    ]),
    `final readonly class ${entry.name}`,
    '{',
    ...body,
    '}',
  ].join('\n');
}

/**
 * A holder of the string constants an enum property accepts.
 *
 * Enums stay `string` on the fields themselves — the gateway adds values
 * between SDK releases and a PHP enum would turn that into a crash — but the
 * values it lists today are worth spelling once so callers can autocomplete
 * them instead of quoting a slug from the docs.
 */
function emitConstants(name, description, values) {
  const out = [...docBlock(prose(description)), `final class ${name}`, '{'];
  for (const value of values) {
    out.push(`    public const ${constantName(value)} = ${quote(value)};`);
  }
  out.push('');
  out.push(
    ...docBlock(['Every value the snapshot lists, in its order.', '', '@var list<string>'], '    '),
  );
  out.push('    public const VALUES = [');
  for (const value of values) out.push(`        ${quote(value)},`);
  out.push('    ];');
  out.push('}');
  return out.join('\n');
}

/** A model file: header, namespace, the imports the body turns out to need. */
function modelFile(name, what, body) {
  const imports = [];
  if (/\bJson::/.test(body)) imports.push(`use ${GENERATED_NAMESPACE}\\Json;`);
  if (/\bLabelledId\b/.test(body)) imports.push(`use ${GENERATED_NAMESPACE}\\LabelledId;`);
  return [
    HEADER(what),
    `namespace ${MODELS_NAMESPACE};`,
    '',
    ...(imports.length > 0 ? [imports.join('\n'), ''] : []),
    body,
    '',
  ].join('\n');
}

