/**
 * A schema reduced to the part of it PHP can see.
 *
 * `birth` and `options` are written out inline in 35-odd request bodies, and
 * two of those copies differ only in a `default` (`KP` defaults the ayanamsa
 * to `krishnamurti`). Validation keywords, defaults and prose change nothing
 * about the generated class, so they are dropped before comparing: what is
 * left is the shape, and equal shapes share one class.
 */
function shapeKey(schema) {
  // At the root, `{"type": ["null", "object"]}` and `{"type": "object"}` are
  // the same class: whether the *field* may be null is the field's business.
  // Inside, nullability is kept — `{a: string}` and `{a: string | null}` are
  // different classes.
  return JSON.stringify(shapeOf(schema, true));
}

function shapeOf(schema, root = false) {
  if (!schema || typeof schema !== 'object') return schema ?? null;
  if (schema.$ref) return { $ref: schema.$ref };
  const out = {};
  if (schema.type !== undefined) {
    let declared = Array.isArray(schema.type) ? [...schema.type].sort() : schema.type;
    if (root && Array.isArray(declared)) {
      const real = declared.filter((t) => t !== 'null');
      declared = real.length === 1 ? real[0] : real.length === 0 ? 'null' : real;
    }
    out.type = declared;
  }
  if (schema.anyOf) out.anyOf = schema.anyOf.map((branch) => shapeOf(branch));
  if (schema.properties) {
    out.properties = {};
    for (const key of Object.keys(schema.properties).sort()) {
      out.properties[key] = shapeOf(schema.properties[key]);
    }
  }
  if (schema.required) out.required = [...schema.required].sort();
  if (schema.items) out.items = shapeOf(schema.items);
  if (schema.additionalProperties === true) out.additionalProperties = true;
  else if (schema.additionalProperties && typeof schema.additionalProperties === 'object') {
    out.additionalProperties = shapeOf(schema.additionalProperties);
  }
  return out;
}

