/**
 * A resolved PHP type.
 *
 * `kind` drives the `fromArray()` / `toArray()` expressions; `declared` is
 * what the promoted property is typed as and `doc` is what PHPDoc says, which
 * is where the generics live — PHP's own `array` says nothing about what is
 * inside it and PHPStan at level 9 insists on knowing.
 */
function type(kind, extra = {}) {
  return { kind, nullable: false, ...extra };
}

/** The PHP type declaration for `t`. */
function declared(t) {
  const q = t.nullable ? '?' : '';
  switch (t.kind) {
    case 'string':
      return `${q}string`;
    case 'int':
      return `${q}int`;
    case 'float':
      return `${q}float`;
    case 'bool':
      return `${q}bool`;
    case 'class':
      return `${q}${t.name}`;
    case 'stringOrClass':
      // A union takes no `?`; null is spelled out.
      return `string|${t.of.name}${t.nullable ? '|null' : ''}`;
    case 'stringList':
    case 'list':
    case 'map':
    case 'json':
      return `${q}array`;
    case 'any':
      // `mixed` already includes null; `?mixed` is a parse error.
      return 'mixed';
    default:
      throw new Error(`unknown kind ${t.kind}`);
  }
}

/** The PHPDoc type for `t`, generics included. */
function docType(t) {
  const suffix = t.nullable && t.kind !== 'any' ? '|null' : '';
  switch (t.kind) {
    case 'string':
      return `string${suffix}`;
    case 'int':
      return `int${suffix}`;
    case 'float':
      return `float${suffix}`;
    case 'bool':
      return `bool${suffix}`;
    case 'class':
      return `${t.name}${suffix}`;
    case 'stringOrClass':
      return `string|${t.of.name}${suffix}`;
    case 'stringList':
      return `list<string>${suffix}`;
    case 'list':
      return `list<${docType(t.of)}>${suffix}`;
    case 'map':
      return `array<string, ${docType(t.of)}>${suffix}`;
    case 'json':
      return `array<string, mixed>${suffix}`;
    case 'any':
      return 'mixed';
    default:
      throw new Error(`unknown kind ${t.kind}`);
  }
}

/** True when PHP's own type declaration already says everything PHPDoc would. */
function needsDocType(t) {
  return ['stringList', 'list', 'map', 'json'].includes(t.kind);
}

/** True when a value of `t` is already array-and-scalar and needs no mapping. */
function writesPlainly(t) {
  if (['string', 'int', 'float', 'bool', 'json', 'any', 'stringList'].includes(t.kind)) return true;
  if (t.kind === 'list' || t.kind === 'map') return writesPlainly(t.of);
  return false;
}

/** The names the nested `foreach`es use, one pair per level. */
function loopNames(depth) {
  if (depth === 0) return ['$key', '$value'];
  if (depth === 1) return ['$innerKey', '$innerValue'];
  return [`$key${depth + 1}`, `$value${depth + 1}`];
}

/** The name a nested closure gives its parameter, one per level. */
function closureName(depth) {
  return depth === 0 ? '$v' : depth === 1 ? '$item' : `$v${depth + 1}`;
}

/**
 * The expression that reads `expr` (a `mixed`) as a `t`.
 *
 * Everything but a map is one expression; maps are a `foreach`, which the
 * caller hoists into a local before the `return new self(…)`.
 */
function readExpr(t, expr, depth = 0) {
  if (t.nullable) {
    switch (t.kind) {
      case 'string':
        return `Json::stringOrNull(${expr})`;
      case 'int':
        return `Json::intOrNull(${expr})`;
      case 'float':
        return `Json::floatOrNull(${expr})`;
      case 'bool':
        return `Json::boolOrNull(${expr})`;
      case 'stringList':
        return `Json::languagesOrNull(${expr})`;
      case 'json':
        return `Json::objectOrNull(${expr})`;
      case 'any':
        return expr;
      default:
        // A class or a list: the guard has to be written out, so `expr` is
        // always a plain variable by the time it gets here.
        return `${expr} === null ? null : ${readNonNull(t, expr, depth)}`;
    }
  }
  return readNonNull(t, expr, depth);
}

function readNonNull(t, expr, depth) {
  switch (t.kind) {
    case 'string':
      return `Json::string(${expr})`;
    case 'int':
      return `Json::int(${expr})`;
    case 'float':
      return `Json::float(${expr})`;
    case 'bool':
      return `Json::bool(${expr})`;
    case 'stringList':
      return `Json::languages(${expr})`;
    case 'json':
      return `Json::object(${expr})`;
    case 'any':
      return expr;
    case 'class':
      return `${t.name}::fromArray(Json::object(${expr}))`;
    case 'stringOrClass':
      return `is_string(${expr}) ? ${expr} : ${t.of.name}::fromArray(Json::object(${expr}))`;
    case 'list': {
      const name = closureName(depth);
      const element = readExpr(t.of, name, depth + 1);
      const cast = `static fn (mixed ${name}): ${declared(t.of)} => ${element}`;
      return `array_map(${cast}, Json::list(${expr}))`;
    }
    default:
      throw new Error(`${t.kind} is read with a foreach, not an expression`);
  }
}

/** Reads a map (and any map nested inside it) into `target`. */
function readMapLines(target, t, source, indent, depth = 0) {
  const [key, value] = loopNames(depth);
  const lines = [
    `${indent}${target} = [];`,
    `${indent}foreach (Json::object(${source}) as ${key} => ${value}) {`,
  ];
  if (t.of.kind === 'map' && !t.of.nullable) {
    const inner = depth === 0 ? '$inner' : `$inner${depth + 1}`;
    lines.push(...readMapLines(inner, t.of, value, `${indent}    `, depth + 1));
    lines.push(`${indent}    ${target}[${key}] = ${inner};`);
  } else {
    lines.push(`${indent}    ${target}[${key}] = ${readExpr(t.of, value, depth + 1)};`);
  }
  lines.push(`${indent}}`);
  return lines;
}

/**
 * The expression that turns a value of `t` back into JSON.
 *
 * Answers `{pre, expr}`: `pre` is the statements that have to run first, which
 * is how a container of containers is written without an un-annotated
 * `array` closure parameter (PHPStan level 9 rejects those).
 */
function writeValue(t, source, varName, indent, depth = 0) {
  if (writesPlainly(t)) return { pre: [], expr: source };
  if (t.kind === 'class') return { pre: [], expr: `${source}->toArray()` };
  if (t.kind === 'stringOrClass') {
    return { pre: [], expr: `is_string(${source}) ? ${source} : ${source}->toArray()` };
  }
  if (t.kind === 'list' || t.kind === 'map') {
    if (t.of.kind === 'class' && !t.of.nullable) {
      const name = closureName(depth);
      const cast = `static fn (${t.of.name} ${name}): array => ${name}->toArray()`;
      return { pre: [], expr: `array_map(${cast}, ${source})` };
    }
    const [key, value] = loopNames(depth);
    const inner = writeValue(t.of, value, `${varName}Item`, `${indent}    `, depth + 1);
    return {
      pre: [
        `${indent}$${varName} = [];`,
        `${indent}foreach (${source} as ${key} => ${value}) {`,
        ...inner.pre,
        `${indent}    $${varName}[${key}] = ${inner.expr};`,
        `${indent}}`,
      ],
      expr: `$${varName}`,
    };
  }
  throw new Error(`cannot write kind ${t.kind}`);
}

